const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const bundle = require('./build-demo.cjs');
const notes = new Map();
function makeNote(spec) {
  const labels = new Map();
  return {...spec, getContent(){return this.content},setContent(value){this.content=value},getLabelValue:name=>labels.get(name),setLabel:(name,value)=>labels.set(name,value),setRelation(){},save(){}};
}
notes.set('twCatalogData',makeNote({content:'[]'}));
const navigationDefaults={shortcuts:[],tools:['searchNotes','showDeletedNotes'],showTree:false,showNative:false};
notes.set('twNavigationData',makeNote({content:JSON.stringify(navigationDefaults)}));
const context={api:{getNote:id=>notes.get(id),createNewNote(spec){const note=makeNote(spec);notes.set(spec.noteId,note);return {note};}}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../src/install-workbench.js'),'utf8'),context);
const pkg=bundle.packages[0];
context.installWorkbench(pkg);
let preferences=JSON.parse(notes.get('twNavigationData').content);
assert.equal(preferences.shortcuts[0].rootId,pkg.rootId);
preferences.shortcuts[0]={...preferences.shortcuts[0],pinned:false,glyph:'📚',expanded:false};
notes.get('twNavigationData').content=JSON.stringify(preferences);
notes.get(pkg.dataId).content='edited workbook retained';
notes.get(pkg.rootId).setLabel('workbenchEnabled','false');
const count=notes.size;
context.installWorkbench(pkg);
assert.equal(notes.size,count);
assert.equal(notes.get(pkg.dataId).content,'edited workbook retained');
assert.equal(notes.get(pkg.rootId).getLabelValue('workbenchEnabled'),'true');
assert.deepEqual(JSON.parse(notes.get('twNavigationData').content),preferences);
const another={...pkg,id:'reference-demo',rootId:'demoReference',rendererId:'demoReferenceUI',dataId:undefined,preparationId:undefined,title:'资料范例',notes:[{noteId:'demoReference',parentNoteId:'root',title:'资料范例',type:'render',content:''},{noteId:'demoReferenceUI',parentNoteId:'demoReference',title:'界面',type:'code',content:''}]};
context.installWorkbench(another);
assert.equal(JSON.parse(notes.get('twNavigationData').content).shortcuts[1].rootId,another.rootId);
assert.equal(notes.get(pkg.dataId).content,'edited workbook retained');
assert.throws(()=>context.installWorkbench({...pkg,id:'unrelated'}),/编号冲突/);
notes.clear();notes.set('twCatalogData',makeNote({content:'[]'}));notes.set('twNavigationData',makeNote({content:JSON.stringify(navigationDefaults)}));notes.set(pkg.dataId,makeNote({content:'existing unrelated data'}));
assert.throws(()=>context.installWorkbench(pkg),/编号冲突/);
assert.equal(notes.size,3);
assert.equal(notes.get(pkg.dataId).content,'existing unrelated data');
assert.throws(()=>context.installWorkbench({...pkg,notes:[{...pkg.notes[0],noteId:'root'}]}),/目录结构/);
assert.throws(()=>context.installWorkbench({...pkg,notes:[pkg.notes[0],{...pkg.notes[1],parentNoteId:'foreign'}]}),/目录结构/);
assert.equal(JSON.parse(notes.get('twCatalogData').content).length,0);
console.log('PASS: generic workbench shortcuts, re-enable preserves navigation/data, identity conflicts do not overwrite.');
